// آیکون برنامه — یک منبع، همهٔ اندازه‌ها.
//
// چرا فایل جداست و چرا SVG:
//   آیکون در سه جا لازم می‌شود (manifest وب، اندروید، فروشگاه) و در
//   اندازه‌های متفاوت. اگر PNGها را دستی می‌ساختم، هر تغییر کوچک
//   یعنی بازساختن دستیِ ۶ فایل و دیر یا زود یکی عقب می‌ماند.
//   اینجا شکل یک بار تعریف می‌شود و scripts/build-icons.js همهٔ
//   اندازه‌ها را از رویش می‌سازد.
//
// چرا این طرح (چهرهٔ کودک روی نارنجی برند):
//   چهار طرح ساخته و در اندازهٔ واقعیِ صفحهٔ گوشی (۴۸px) کنار هم
//   دیده شدند. حرف «پ» چیزی دربارهٔ آموزش نمی‌گفت؛ جوانه در اندازهٔ
//   کوچک کم‌رمق می‌شد؛ بلوک‌های رنگی شبیه آیکون برنامهٔ اداری بود.
//   چهره تنها طرحی بود که در ۴۸px هم بی‌درنگ «برنامهٔ کودک» خوانده
//   می‌شد. والدی که در کافه‌بازار فهرست را بالا و پایین می‌کند،
//   کمتر از یک ثانیه به هر آیکون نگاه می‌کند.

const BRAND = '#E4572E';
const SKIN = '#F5D3B5';
const INK = '#2B2A33';
const STAR = '#F4B942';

/**
 * آیکون برنامه به‌صورت SVG.
 *
 * @param {object} opts
 * @param {boolean} opts.maskable آیا نسخهٔ maskable اندروید است؟
 *   اندروید آیکون را می‌بُرد (دایره، مربع گرد، قطره…) و فقط ۸۰٪
 *   مرکزی تضمین‌شده دیده می‌شود. در این حالت طرح کوچک‌تر و پس‌زمینه
 *   تا لبه کشیده می‌شود تا گوشه‌ها بریده شوند نه خودِ چهره.
 * @param {boolean} opts.rounded گوشهٔ گرد برای وب/آی‌اواس.
 */
export function appIcon({ maskable = false, rounded = true } = {}) {
  // در حالت maskable طرح در ۸۰٪ مرکزی می‌نشیند (حاشیهٔ امن).
  const s = maskable ? 0.78 : 1;
  const t = maskable ? `translate(${256 * (1 - s)} ${256 * (1 - s)}) scale(${s})` : '';
  const radius = maskable ? 0 : rounded ? 112 : 0;

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
  <rect width="512" height="512" rx="${radius}" fill="${BRAND}"/>
  <g transform="${t}">
    <circle cx="256" cy="196" r="88" fill="${SKIN}"/>
    <circle cx="227" cy="188" r="13.5" fill="${INK}"/>
    <circle cx="285" cy="188" r="13.5" fill="${INK}"/>
    <path d="M220 230 q36 32 72 0" fill="none" stroke="${INK}"
      stroke-width="15" stroke-linecap="round"/>
    <path d="M256 300 q92 0 92 132 h-184 q0 -132 92 -132z" fill="${STAR}"/>
  </g>
</svg>`;
}
