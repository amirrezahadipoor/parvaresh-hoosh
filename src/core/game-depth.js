// عمقِ بازی‌ها — منطقِ خالصِ پاداشِ رشته (§۷.۴ — گسترش به درخواستِ مالک).
//
// ── چرا ──────────────────────────────────────────────────────────────
// بازیِ امتیازیِ «هر پاسخ یک امتیاز» یکنواخت است: کودک فرقی بین
// «درستِ پیاپی» و «درستِ پراکنده» نمی‌بیند. رشتهٔ پاسخ‌های درست یک
// شعله می‌سازد: پاسخِ درستِ پیاپی امتیازِ بیشتری می‌دهد (تا سقف) —
// یعنی دقتِ پیوسته پاداش دارد، نه فقط سرعت.
//
// ⚠ بدونِ اقتصادِ سکه (قانون): پاداش فقط عددِ همان بازی است.
// ⚠ خالص و بی‌واسطه، تا گارد بتواند مستقیم آزمونش کند.
//
// منحنیِ پاداش: پاسخِ اول +۱، دوم +۲ (شعله روشن)، سوم +۳، چهارم +۴
// و بعد سقفِ +۴. بیش از چهارِ پیاپی پاداشِ بیشتر نمی‌دهد — شعله باید
// «داغ» بماند، نه بی‌نهایت بزرگ شود.

/** پاداشِ رشته: ۰، ۱، ۲، ۳ و بعد سقفِ ۳. */
export function streakBonus(streak) {
  if (!Number.isInteger(streak) || streak < 2) return 0;
  return Math.min(streak - 1, 3);
}

/** مجموعِ امتیازِ یک پاسخِ درست با رشتهٔ داده‌شده. */
export function pointsFor(streak) {
  return 1 + streakBonus(streak);
}

/** بلوک‌هایِ برجِ پاسخ — سقفِ نمایشی، تا در صفحهٔ کوتاه سرریز نشود. */
export const TOWER_CAP = 10;
export function towerBlocks(score) {
  return Math.min(Math.max(0, score | 0), TOWER_CAP);
}
