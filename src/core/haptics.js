// لرزشِ مهربان — بازخوردِ لمسیِ «آفرین».
//
// ── چرا ──────────────────────────────────────────────────────────────
// قانونِ برنامه: «هرجا صدا نیست، راهنمای دیداری باشد» و برنامه باید
// کاملاً بی‌صدا هم کار کند. جشنِ پاسخِ درست در حالتِ بی‌صدا فقط چشم
// بود؛ لرزش همان «آفرین» را به زبانِ پوست می‌گوید — کانالی که صدا
// ندارد و کودکِ نشنونده هم می‌گیردش.
//
// ⚠ عمداً «مهربان» است: یک تپِ ۱۵ms، فقط روی پاسخِ درست. هرگز روی
// پاسخِ غلط (لرزشِ تنبیهی ممنوع — همان قانونِ «هرگز ضربدرِ قرمز»)
// و هرگز الگویِ پالسِ تکراریِ ۲۰۰ms که آزاردهنده است.
//
// ⚠ پشتِ تنظیمِ والدین است (داخلِ صفحهٔ تنظیمات، که خودش پشتِ
// دروازهٔ والدین است) و در جایی که پشتیبانی نیست بی‌اثر است:
// دسکتاپ، iOS (تا نسخه‌های اخیر)، و مرورگرهایی که vibrate را
// تعریف نمی‌کنند — feature-detect، نه try/catchِ کور.

import * as store from './storage.js';

/**
 * یک تپِ کوتاه روی پاسخِ درست.
 * اگر والد لرزش را خاموش کرده یا دستگاه پشتیبانی نکند، هیچ.
 */
export function gentleBuzz() {
  const s = store.getState();
  if (!s.vibrate) return;
  if (typeof navigator === 'undefined' || typeof navigator.vibrate !== 'function') return;
  try {
    navigator.vibrate(15);
  } catch {
    /* برخی مرورگرها اجازه نمی‌دهند — بی‌صدا رد شو */
  }
}
