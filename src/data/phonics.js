/** واژه را از روی نوشتارش پیدا می‌کند. */
export function soundsOf(word) {
  return SOUND_MAP.find((w) => w.word === word) || null;
}

/** همهٔ صداهای یک واژه، بدون مرز بخش. */
export function flatSounds(entry) {
  return entry.syllables.flat();
}

/** تعداد بخش‌های واژه. */
export function syllableCount(entry) {
  return entry.syllables.length;
}

/** متن یک بخش، همان‌طور که نوشته می‌شود. */
export function syllableText(syl) {
  return syl.map((s) => s.g).join('');
}

/**
 * واژه‌های مناسب یک سطح دشواری.
 * @param {object} opts
 * @param {number} [opts.maxSounds] بیشترین تعداد صدا
 * @param {number} [opts.maxSyllables] بیشترین تعداد بخش
 * @param {number} [opts.minSyllables] کمترین تعداد بخش
 * @param {boolean} [opts.longVowelOnly] فقط مصوت بلند (ساده‌تر — نوشته می‌شود)
 * @param {(w:string)=>boolean} [opts.readable] آیا حروفش آموزش داده شده؟
 */
export function pickWords(opts = {}) {
  const { maxSounds = 99, maxSyllables = 99, minSyllables = 1, longVowelOnly = false, readable } = opts;
  return SOUND_MAP.filter((e) => {
    const all = flatSounds(e);
    if (all.length > maxSounds) return false;
    if (e.syllables.length > maxSyllables) return false;
    if (e.syllables.length < minSyllables) return false;
    // مصوت کوتاه سخت‌تر است چون نوشته نمی‌شود
    if (longVowelOnly && all.some((s) => s.v && SHORT_VOWELS[s.v])) return false;
    if (readable && !readable(e.word)) return false;
    return true;
  });
}

/**
 * «قافیه» (rime) یک واژه = از آخرین مصوت تا پایان.
 *
 * چرا این تابع لازم شد:
 * جدول Reading Rockets («سنی که ۸۰–۹۰٪ کودکان مهارت را دارند»)
 * تشخیص قافیه را در ۵ سالگی می‌گذارد — یعنی *پیش از* بخش‌کردن و
 * پیش از تجزیهٔ واج. تا امروز برنامه هیچ تمرین قافیه‌ای نداشت و
 * مستقیم سراغ صداکشی می‌رفت؛ یعنی یک پلهٔ کاملِ رشدی جا افتاده بود.
 *
 * قافیه را از روی *صدا* می‌گیریم نه املا: «ماهی» و «طوطی» هر دو با
 * «ای» تمام می‌شوند، هرچند نویسهٔ آخرشان یکی نیست.
 */
export function rimeKey(entry) {
  const all = flatSounds(entry);
  let i = -1;
  for (let k = all.length - 1; k >= 0; k--) {
    if (all[k].v) {
      i = k;
      break;
    }
  }
  if (i < 0) return null;
  return all.slice(i).map((s) => s.s).join('·');
}

/**
 * خانواده‌های هم‌قافیه: کلیدِ قافیه → فهرست واژه‌ها.
 * @param {(w:string)=>boolean} [filter] صافیِ اختیاری (خواندنی؟ تصویر دارد؟)
 */
export function rhymeFamilies(filter) {
  const map = new Map();
  for (const e of SOUND_MAP) {
    if (filter && !filter(e.word)) continue;
    const key = rimeKey(e);
    if (!key) continue;
    if (!map.has(key)) map.set(key, []);
    map.get(key).push(e.word);
  }
  return map;
}

/**
 * صدای آغازینِ واژه — نخستین صدای بخش اول.
 * ۵٫۵ سالگی: «جدا کردن صدای اول» (Reading Rockets). این تمرین با
 * «کدام کلمه با ب شروع می‌شود؟» فرق دارد: آنجا کودک *نویسه* را
 * می‌بیند، اینجا باید از تصویر به صدا برسد.
 */
export function firstSound(entry) {
  return entry.syllables[0][0];
}

/** بررسی سلامت داده — اعتبارسنج استفاده می‌کند. */
export function auditPhonics() {
  const problems = [];
  const seen = new Set();
  for (const e of SOUND_MAP) {
    if (seen.has(e.word)) problems.push(`${e.word}: تکراری است`);
    seen.add(e.word);

    if (!e.syllables.length) {
      problems.push(`${e.word}: بدون بخش`);
      continue;
    }
    const all = flatSounds(e);
    if (all.length < 2) problems.push(`${e.word}: کمتر از دو صدا`);

    // نوشتار بازسازی‌شده باید با خود واژه یکی باشد.
    // این مهم‌ترین بررسی است: اگر نقشهٔ صدا با املا نخواند، کودک
    // چیزی می‌بیند که با آنچه می‌شنود نمی‌خواند.
    const rebuilt = all.map((s) => s.g).join('');
    const normalized = e.word.replace(/آ/g, 'ا');
    if (rebuilt !== normalized) {
      problems.push(`${e.word}: نقشهٔ صدا «${rebuilt}» با املا نمی‌خواند`);
    }

    // هر بخش باید دقیقاً یک مصوت داشته باشد — تعریف خودِ «بخش».
    for (const [i, syl] of e.syllables.entries()) {
      const vowels = syl.filter((s) => s.v);
      if (vowels.length !== 1) {
        problems.push(`${e.word}: بخش ${i + 1} باید یک مصوت داشته باشد، ${vowels.length} دارد`);
      }
    }
  }
  return problems;
}
