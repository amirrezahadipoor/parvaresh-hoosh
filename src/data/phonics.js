// موتور واج‌شناسی فارسی — صداکشی، بخش‌کردن، ترکیب.
//
// چرا این فایل قلب پروژه است:
// تا پیش از این، حوزهٔ خواندن پنج نوع تمرین داشت که همه در سطح
// «شناخت حرف» می‌ماندند: این حرف کدام است، رویش بکش، در کلمه پیدایش
// کن، حروفش را بشمار. هیچ‌کدام کودک را به **خواندن** نمی‌رساند.
// کودک حرف را می‌شناخت ولی کلمه را نمی‌خواند.
//
// حلقهٔ گمشده «صداکشی» است: بـ ا د ← باد.
//
// منابع (روش مدرسهٔ ایران):
//   kashkoolaneh.blogfa.com/post/192 — اول جدول ترکیب صامت+مصوت
//   (رَ، را، رو)، بعد افزودن صامت (رَد، رام، رود)، بعد کلمهٔ کامل:
//   «ما» + «دَ» + «ر» ← مادَر. معلم تند اشاره می‌کند و کودک می‌خواند.
//   karamoz.blogfa.com/post/60 — بخش کردن و صداکشی با انگشتان دست.
//
// منابع (پژوهش جهانی):
//   Herlambang 2020 — **ترکیب پیش از تجزیه** آموزش داده شود.
//   گروه «ترکیب-اول» ۶۶٪ موفقیت در برابر ۴۷٪ گروه «تجزیه-اول».
//   Louisa Moats 2024 / IES REL — توالی: هجا ← آغازه و قافیه ← واج.
//   ساختار CV و VC پیش از CVC؛ CVC پیش از خوشهٔ همخوان.
//
// تصمیم مهم دربارهٔ اعراب:
// فارسی مصوت کوتاه را نمی‌نویسد. «سبد» سه حرف دارد ولی پنج صدا:
// س‑َ‑ب‑َ‑د. برای صداکشی باید بدانیم مصوت کوتاه کجاست. پس هر واژه
// یک «نقشهٔ صدا» دستی دارد. این تنها جایی است که داده باید صریح
// باشد — حدس‌زدنِ مصوت کوتاه از روی املا در فارسی ممکن نیست.

/** مصوت‌های کوتاه — نوشته نمی‌شوند ولی شنیده می‌شوند. */
export const SHORT_VOWELS = Object.freeze({
  a: { mark: 'َ', name: 'زبر', display: 'اَ' },
  e: { mark: 'ِ', name: 'زیر', display: 'اِ' },
  o: { mark: 'ُ', name: 'پیش', display: 'اُ' },
});

/** مصوت‌های بلند — نوشته می‌شوند. */
export const LONG_VOWELS = Object.freeze({
  A: { letter: 'ا', name: 'آ', display: 'آ' },
  i: { letter: 'ی', name: 'ای', display: 'ای' },
  u: { letter: 'و', name: 'او', display: 'او' },
});

/**
 * نقشهٔ صدای واژه‌ها.
 *
 * قالب: واژه → آرایهٔ بخش‌ها. هر بخش آرایه‌ای از صداهاست.
 * هر صدا: { g: نگاشتِ نوشتاری, s: نام صدا, v: مصوت؟ }
 *
 * `g` همان چیزی است که روی صفحه نشان داده می‌شود (گرافم).
 * برای مصوت کوتاه `g` خالی است چون نوشته نمی‌شود — و دقیقاً همین
 * است که خواندن فارسی را برای کودک سخت می‌کند و باید آموزش داده شود.
 */
const W = (word, syllables, meaning) => ({ word, syllables, meaning });
const C = (g) => ({ g, s: g }); // همخوان: نوشته می‌شود
const V = (v) => ({ g: '', s: SHORT_VOWELS[v].display, v }); // مصوت کوتاه: نوشته نمی‌شود
const L = (v) => ({ g: LONG_VOWELS[v].letter, s: LONG_VOWELS[v].display, v }); // مصوت بلند
// «هـ» پایانی («خانه»، «گربه»): صدایش مصوت کوتاه اِ است ولی برخلاف
// مصوت‌های کوتاه دیگر **نوشته می‌شود**. اگر آن را بدون گرافم بگذاریم،
// نوشتار بازسازی‌شده با املا نمی‌خواند و کودک حرفی می‌بیند که در
// صداکشی وجود ندارد.
const He = () => ({ g: 'ه', s: SHORT_VOWELS.e.display, v: 'e' });
// «و» در «حوض» و «خواهر»: نوشته می‌شود ولی صدایش مصوت کوتاه اُ است.
// همان استثنای «هـ» پایانی، در سمت دیگر.
const Wo = () => ({ g: 'و', s: SHORT_VOWELS.o.display, v: 'o' });

